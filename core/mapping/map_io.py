"""Map I/O and coordinate transforms for NIDAR AirMouse."""
from __future__ import annotations

import json
from dataclasses import dataclass
from pathlib import Path
from typing import List, Tuple
import numpy as np


@dataclass
class MapMetadata:
    name: str
    seed: int
    mode: str
    rows: int
    cols: int
    cell_size_m: float
    start_cell: Tuple[int, int]
    start_world: Tuple[float, float]
    # Note: ground-truth survivor positions are kept in MapMetadata solely for
    # simulator backend initialization and evaluation scoring. Autonomy algorithms
    # never receive or inspect these coordinates.
    true_survivors: List[Tuple[float, float]]


def load_map_file(path: str | Path) -> Tuple[np.ndarray, MapMetadata]:
    """Load procedural map generated by generate_maps.py.
    
    Returns:
        grid: np.ndarray (shape: rows x cols) with 0=free, 1=wall, 2=furniture
        metadata: MapMetadata containing dimensions, resolution, and start world coordinate
    """
    p = Path(path)
    if not p.exists():
        raise FileNotFoundError(f"Map file not found: {p}")

    data = json.loads(p.read_text())
    grid = np.array(data["grid"], dtype=np.uint8)
    rows, cols = grid.shape
    cell_size = float(data.get("cell_size_m", 1.0))
    start_cell = tuple(data["start"])
    start_world = tuple(data.get("start_world", cell_to_world(start_cell[0], start_cell[1], rows, cell_size)))

    people_world = []
    for p_info in data.get("people", []):
        if "world" in p_info:
            people_world.append(tuple(p_info["world"]))
        elif "cell" in p_info:
            cx, cy = p_info["cell"]
            people_world.append(cell_to_world(cx, cy, rows, cell_size))

    meta = MapMetadata(
        name=data.get("name", p.stem),
        seed=int(data.get("seed", 0)),
        mode=data.get("mode", "house"),
        rows=rows,
        cols=cols,
        cell_size_m=cell_size,
        start_cell=start_cell,
        start_world=start_world,
        true_survivors=people_world,
    )
    return grid, meta


def cell_to_world(cx: int | float, cy: int | float, rows: int, cell_size_m: float = 1.0) -> Tuple[float, float]:
    """Converts grid cell indices (col x, row y) to metric world coordinates (X, Y).
    Matches generate_maps.py: row 0 is top (max world Y).
    """
    wx = (cx + 0.5) * cell_size_m
    wy = (rows - cy - 0.5) * cell_size_m
    return wx, wy


def world_to_cell(wx: float, wy: float, rows: int, cell_size_m: float = 1.0) -> Tuple[int, int]:
    """Converts metric world coordinates (X, Y) to grid cell indices (col x, row y)."""
    cx = int(wx / cell_size_m)
    cy = int(rows - (wy / cell_size_m))
    return cx, cy

